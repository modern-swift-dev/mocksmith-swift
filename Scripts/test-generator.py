#!/usr/bin/env python3
"""Check generation and incremental output stability using a built generator.

Run after `swift build --product MocksmithGenerator`, or pass its executable path.
"""

import argparse
import json
import os
from pathlib import Path
import shutil
import subprocess
from tempfile import TemporaryDirectory

EMPTY_OUTPUT = "// Generated by MocksmithGenerator. Do not edit.\n"


def generated_name(source):
    """Mirrors generatedFileName(for:) in the generator and the build plugin."""
    value = 14_695_981_039_346_656_037
    for byte in str(source).encode():
        value = ((value ^ byte) * 1_099_511_628_211) % 2**64
    return f"{Path(source).stem}.{value:x}.generated.swift"


def read_generated(directory):
    """Concatenates a generator output directory's files in name order."""
    return "".join(path.read_text() for path in sorted(directory.glob("*.generated.swift")))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("generator", nargs="?", type=Path)
    arguments = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    if arguments.generator is None:
        binary_path = Path(subprocess.check_output(
            ["swift", "build", "--show-bin-path"], cwd=root, text=True
        ).strip())
        generator = binary_path / "MocksmithGenerator"
    else:
        generator = arguments.generator.resolve()
    if not generator.is_file():
        raise FileNotFoundError(generator)

    with TemporaryDirectory(prefix="mocksmith-generator-tests-") as directory:
        directory = Path(directory)
        declarations = directory / "Services.swift"
        unrelated = directory / "Unrelated.swift"
        output = directory / "Generated"
        cache = directory / "Generated.cache.json"
        declarations.write_text("""import Mocksmith
@Mockable(.buildPlugin) protocol FastService {
    func value() -> Int
}
@Mockable(.macro) protocol MacroService {}
@Mockable protocol DefaultService {}
protocol Parent {
    func inherited() -> String
}
@Mockable protocol Child: Parent {}
""")
        unrelated.write_text("func unrelated() -> Int { 1 }\n")
        declarations_output = output / generated_name(declarations)
        command = [
            str(generator), "--output-directory", str(output),
            "--target-module", "Fixture", "--module", "Fixture",
            str(declarations), str(unrelated),
        ]

        def generate():
            subprocess.run(command, cwd=root, check=True)
            return read_generated(output)

        def parsed_paths(arguments=None):
            """Runs the generator and returns the sources it parsed."""
            result = subprocess.run(
                arguments or command, cwd=root, check=True, text=True, capture_output=True,
                env={**os.environ, "MOCKSMITH_GENERATOR_TRACE_PARSING": "1"},
            )
            prefix = "MocksmithGenerator: parsed "
            return [line[len(prefix):] for line in result.stderr.splitlines() if line.startswith(prefix)]

        generated = generate()
        assert "class FastServiceMock:" in generated
        assert "class ChildMock:" in generated
        assert "func inherited() -> String" in generated
        assert "MacroServiceMock" not in generated
        assert "DefaultServiceMock" in generated
        assert "@_MocksmithResolved" not in generated
        assert sorted(path.name for path in output.iterdir()) == sorted(map(generated_name, [declarations, unrelated]))
        assert (output / generated_name(unrelated)).read_text() == EMPTY_OUTPUT
        cached = cache.read_bytes()

        # Large dependency graphs exceed NSTask's argument limit, so the plugin
        # passes its arguments through a response file.
        response_output = directory / "Response"
        response_file = directory / "arguments.txt"
        response_file.write_text("\n".join([
            "--output-directory", str(response_output),
            "--target-module", "Fixture", "--module", "Fixture",
            str(declarations), str(unrelated),
        ]))
        subprocess.run([str(generator), f"@{response_file}"], cwd=root, check=True)
        assert read_generated(response_output) == generated

        # NSTask rejects more than 4096 arguments; a response file must carry
        # every entry beyond that limit.
        many = directory / "Many"
        many.mkdir()
        many_paths = []
        for index in range(4200):
            many_paths.append(many / f"File{index}.swift")
            many_paths[-1].write_text(f"func value{index}() -> Int {{ {index} }}\n")
        many_paths[-1].write_text("import Mocksmith\n@Mockable protocol LastService { func value() -> Int }\n")
        many_output = many / "Generated"
        many_arguments = many / "arguments.txt"
        many_arguments.write_text("\n".join([
            "--output-directory", str(many_output), "--target-module", "Many", "--module", "Many", *map(str, many_paths),
        ]))
        subprocess.run([str(generator), f"@{many_arguments}"], cwd=root, check=True)
        assert "class LastServiceMock:" in (many_output / generated_name(many_paths[-1])).read_text()
        assert len(list(many_output.iterdir())) == len(many_paths)

        # Each target source gets its own generated file, so editing one protocol
        # leaves the other outputs' bytes and timestamps alone. Outputs of removed
        # sources, including the single file older versions wrote, are deleted.
        split = directory / "Split"
        split.mkdir()
        first = split / "First.swift"
        first.write_text("import Mocksmith\n@Mockable protocol FirstService { func value() -> Int }\n")
        second = split / "Second.swift"
        second.write_text("import Mocksmith\n@Mockable protocol SecondService { func value() -> Int }\n")
        plain = split / "Plain.swift"
        plain.write_text("func plain() {}\n")
        split_output = split / "Generated"
        split_output.mkdir()
        (split_output / "Mocksmith.generated.swift").write_text("// Output of an older generator\n")
        (split_output / "Unmanaged.swift").write_text("")
        split_command = [
            str(generator), "--output-directory", str(split_output), "--target-module", "Split",
            "--module", "Split", str(first), str(second), str(plain),
        ]
        subprocess.run(split_command, cwd=root, check=True)
        split_outputs = {source: split_output / generated_name(source) for source in [first, second, plain]}
        assert sorted(path.name for path in split_output.glob("*.generated.swift")) == sorted(
            path.name for path in split_outputs.values()
        )
        assert (split_output / "Unmanaged.swift").exists()
        assert "class FirstServiceMock:" in split_outputs[first].read_text()
        assert "SecondServiceMock" not in split_outputs[first].read_text()
        assert "class SecondServiceMock:" in split_outputs[second].read_text()
        assert split_outputs[plain].read_text() == EMPTY_OUTPUT
        for path in split_outputs.values():
            os.utime(path, ns=(1_000_000_000, 1_000_000_000))
        untouched = {source: split_outputs[source].read_bytes() for source in [second, plain]}
        first.write_text(first.read_text().replace("-> Int", "-> String"))
        subprocess.run(split_command, cwd=root, check=True)
        assert "func value() -> String" in split_outputs[first].read_text()
        assert split_outputs[first].stat().st_mtime_ns != 1_000_000_000
        for source, data in untouched.items():
            assert split_outputs[source].read_bytes() == data
            assert split_outputs[source].stat().st_mtime_ns == 1_000_000_000
        split_command.remove(str(second))
        subprocess.run(split_command, cwd=root, check=True)
        assert not split_outputs[second].exists()
        assert split_outputs[first].exists()

        # A prebuild plugin must expose only Swift sources, never its JSON cache.
        prebuild_output = directory / "GeneratedSources"
        prebuild_cache = directory / "PrivateCache" / "generation.json"
        prebuild_command = [
            str(generator), "--output-directory", str(prebuild_output),
            "--cache", str(prebuild_cache), "--target-module", "Fixture",
            "--module", "Fixture", str(declarations), str(unrelated),
        ]
        subprocess.run(prebuild_command, cwd=root, check=True)
        assert read_generated(prebuild_output) == generated
        assert prebuild_cache.is_file()
        prebuild_files = sorted(prebuild_output.iterdir())
        assert [path.name for path in prebuild_files] == sorted(map(generated_name, [declarations, unrelated]))
        for path in prebuild_files + [prebuild_cache]:
            os.utime(path, ns=(1_000_000_000, 1_000_000_000))
        subprocess.run(prebuild_command, cwd=root, check=True)
        for path in prebuild_files + [prebuild_cache]:
            assert path.stat().st_mtime_ns == 1_000_000_000
        result = subprocess.run([str(generator), "--cache"], capture_output=True, text=True)
        assert result.returncode == 2
        assert "missing value after --cache" in result.stderr

        # A fixed timestamp detects rewrites without timing-dependent sleeps.
        os.utime(declarations_output, ns=(1_000_000_000, 1_000_000_000))
        os.utime(cache, ns=(1_000_000_000, 1_000_000_000))
        unchanged_mtime = declarations_output.stat().st_mtime_ns
        unchanged_cache_mtime = cache.stat().st_mtime_ns
        assert generate() == generated
        assert declarations_output.stat().st_mtime_ns == unchanged_mtime
        assert cache.read_bytes() == cached
        assert cache.stat().st_mtime_ns == unchanged_cache_mtime

        unrelated.write_text("func unrelated() -> Int { 2 }\n")
        assert generate() == generated
        assert declarations_output.stat().st_mtime_ns == unchanged_mtime
        assert cache.read_bytes() == cached
        assert cache.stat().st_mtime_ns == unchanged_cache_mtime

        declarations.write_text(declarations.read_text().replace(
            "func value() -> Int", "func value() -> String"
        ))
        updated = generate()
        assert updated != generated
        assert "func value() -> String" in updated
        assert declarations_output.stat().st_mtime_ns != unchanged_mtime
        assert cache.read_bytes() != cached

        # Imports and access affect generated source even without a member edit.
        for old, new in [
            ("import Mocksmith", "import Mocksmith\nimport Foundation"),
            ("protocol FastService", "public protocol FastService"),
        ]:
            cached = cache.read_bytes()
            previous = updated
            declarations.write_text(declarations.read_text().replace(old, new))
            updated = generate()
            assert updated != previous
            assert cache.read_bytes() != cached

        valid_cache = json.loads(cache.read_text())
        cache.write_text("invalid JSON")
        assert generate() == updated
        assert json.loads(cache.read_text()) == valid_cache
        cache.unlink()
        assert generate() == updated
        assert json.loads(cache.read_text()) == valid_cache

        # Simulate replacement of the build tool at the same executable path.
        copied_generator = directory / "MocksmithGenerator"
        shutil.copy2(generator, copied_generator)
        command[0] = str(copied_generator)
        assert generate() == updated
        previous_identity = json.loads(cache.read_text())["generator"]
        poisoned_cache = json.loads(cache.read_text())
        poisoned_cache["files"][str(declarations)]["source"] = "// stale cached renderer output\n" + updated
        cache.write_text(json.dumps(poisoned_cache))
        executable_stat = copied_generator.stat()
        os.utime(copied_generator, ns=(
            executable_stat.st_atime_ns, executable_stat.st_mtime_ns + 2_000_000_000
        ))
        assert generate() == updated
        assert json.loads(cache.read_text())["generator"] != previous_identity
        assert "stale cached renderer output" not in cache.read_text()
        command[0] = str(generator)

        # A source-content snapshot skips parsing without relying on file mtimes.
        parent = directory / "Parent.swift"
        parent.write_text("public protocol Parent { func first() -> Int }\n")
        declarations.write_text("""import Mocksmith
import Dependency
@Mockable protocol Child: Parent {}
""")
        command.extend(["--module", "Dependency", str(parent)])
        inherited = generate()
        assert "func first() -> Int" in inherited
        parent_stat = parent.stat()
        parent.write_text(parent.read_text().replace("first", "other"))
        os.utime(parent, ns=(parent_stat.st_atime_ns, parent_stat.st_mtime_ns))
        assert parent.stat().st_size == parent_stat.st_size
        inherited = generate()
        assert "func other() -> Int" in inherited
        assert "func first() -> Int" not in inherited

        # An inheriting target's no-op rerun compares its snapshot, including
        # dependency sources, before parsing anything.
        assert parsed_paths() == []
        assert read_generated(output) == inherited
        parent.write_text(parent.read_text() + "\n")
        assert str(declarations) in parsed_paths()
        assert read_generated(output) == inherited

        # A cache miss parses only the dependency files that inherited-protocol
        # resolution needs, not every file that declares some protocol.
        lazy = directory / "Lazy"
        lazy.mkdir()
        lazy_child = lazy / "Child.swift"
        lazy_child.write_text("import Mocksmith\nimport LazyDependency\n@Mockable protocol LazyChild: LazyParent {}\n")
        lazy_local = lazy / "Local.swift"
        lazy_local.write_text("protocol LocalUnrelated {}\n")
        lazy_parent = lazy / "LazyParent.swift"
        lazy_parent.write_text("public protocol LazyParent: LazyGrandparent { func parent() }\n")
        lazy_grandparent = lazy / "LazyGrandparent.swift"
        # A comment hides the declared name from the lexical index, so the file is
        # parsed regardless of the name being resolved.
        lazy_grandparent.write_text("public protocol /* opaque */ LazyGrandparent { func grandparent() }\n")
        lazy_unrelated = []
        for index in range(3):
            lazy_unrelated.append(lazy / f"Unrelated{index}.swift")
            lazy_unrelated[-1].write_text(f"public protocol Unrelated{index} {{}}\npublic typealias Alias{index} = Unrelated{index}\n")
        lazy_output = lazy / "Generated"
        lazy_command = [
            str(generator), "--output-directory", str(lazy_output), "--target-module", "LazyFixture",
            "--module", "LazyFixture", str(lazy_child), str(lazy_local),
            "--module", "LazyDependency", str(lazy_parent), str(lazy_grandparent),
            *map(str, lazy_unrelated),
        ]
        assert sorted(parsed_paths(lazy_command)) == sorted(map(str, [lazy_child, lazy_parent, lazy_grandparent]))
        assert "func parent()" in read_generated(lazy_output)
        assert "func grandparent()" in read_generated(lazy_output)

        # Many mocks share parents, reached through diamonds, aliases, and in
        # different orders. Each mock still gets every requirement exactly once,
        # parents first.
        shared = directory / "Shared"
        shared.mkdir()
        shared_base = shared / "Base.swift"
        shared_base.write_text("""public protocol SharedRoot { func root() -> Int }
public protocol SharedLeft: SharedRoot { func left() -> Int }
public protocol SharedRight: SharedRoot, Sendable {
    func right() -> Int
    func root() -> Int
}
public typealias SharedBoth = SharedLeft & SharedRight
""")
        shared_children = shared / "Children.swift"
        shared_children.write_text("import Mocksmith\nimport SharedBase\n" + "".join(
            f"@Mockable protocol Shared{index}: {'SharedBoth' if index % 2 else 'SharedRight, SharedLeft'} {{ func own() }}\n"
            for index in range(40)
        ))
        shared_output = shared / "Generated"
        subprocess.run([
            str(generator), "--output-directory", str(shared_output), "--target-module", "SharedFixture",
            "--module", "SharedFixture", str(shared_children), "--module", "SharedBase", str(shared_base),
        ], cwd=root, check=True)
        shared_mocks = read_generated(shared_output).split("final class Shared")[1:]
        assert len(shared_mocks) == 40
        for index, mock in enumerate(sorted(shared_mocks, key=lambda text: int(text.split("Mock")[0]))):
            names = ["root", "right", "left"] if index % 2 == 0 else ["root", "left", "right"]
            positions = [mock.index(f'(name: "{name}")') for name in names + ["own"]]
            assert positions == sorted(positions), (index, names)
            assert all(mock.count(f'(name: "{name}")') == 1 for name in names + ["own"])

        # Inherited protocols resolve through imports inside #if clauses and
        # through modules that imported modules re-export, transitively.
        reexport = directory / "Reexport"
        reexport.mkdir()
        reexport_child = reexport / "Child.swift"
        reexport_child.write_text("""import Mocksmith
#if canImport(Conditional)
import Conditional
#endif
import Facade
@Mockable protocol ConditionalChild: ConditionalParent {}
@Mockable protocol ReexportedChild: ReexportedParent {}
""")
        conditional_parent = reexport / "ConditionalParent.swift"
        conditional_parent.write_text("public protocol ConditionalParent { func conditional() -> Int }\n")
        facade = reexport / "Facade.swift"
        facade.write_text("@_exported import Middle\n")
        middle = reexport / "Middle.swift"
        middle.write_text("#if true\n@_exported public import Core\n#endif\n")
        core = reexport / "Core.swift"
        core.write_text("public protocol ReexportedParent { func reexported() -> Int }\n")
        reexport_output = reexport / "Generated"
        reexport_command = [
            str(generator), "--output-directory", str(reexport_output), "--target-module", "ReexportFixture",
            "--module", "ReexportFixture", str(reexport_child),
            "--module", "Conditional", str(conditional_parent),
            "--module", "Facade", str(facade), "--module", "Middle", str(middle), "--module", "Core", str(core),
        ]
        subprocess.run(reexport_command, cwd=root, check=True)
        reexported = read_generated(reexport_output)
        assert "func conditional() -> Int" in reexported
        assert "func reexported() -> Int" in reexported
        assert "import Core" in reexported
        assert "#if canImport(Conditional)" in reexported
        # A plain import does not re-export, and must invalidate the cache even
        # though the file no longer mentions a protocol.
        middle.write_text("public import Core\n")
        result = subprocess.run(reexport_command, cwd=root, text=True, capture_output=True)
        assert result.returncode != 0
        assert "cannot resolve inherited protocol or composition alias 'ReexportedParent'" in result.stderr

        # Files that were absent from the snapshot must still be read each run.
        unrelated.write_text("@Mockable protocol AddedService {}\n")
        assert "AddedServiceMock" in generate()
        unrelated.write_text("func unrelated() -> Int { 3 }\n")
        assert generate() == inherited

        added = directory / "Added.swift"
        added.write_text("@Mockable protocol NewService {}\n")
        command.insert(command.index("--module", 6), str(added))
        assert "NewServiceMock" in generate()
        command.remove(str(added))
        added.unlink()
        assert generate() == inherited

        # Deleting a required parent cannot reuse the previous successful cache.
        parent_source = parent.read_text()
        parent.unlink()
        command.remove(str(parent))
        command.extend([str(unrelated)])
        missing_parent = subprocess.run(command, cwd=root, text=True, capture_output=True)
        assert missing_parent.returncode != 0
        assert "Parent" in missing_parent.stderr
        command[-1] = str(parent)
        parent.write_text(parent_source)
        assert generate() == inherited

        # Target and available-module identities are part of cache validity.
        command[4] = "Dependency"
        assert "ChildMock" not in generate()
        command[4] = "Fixture"
        assert generate() == inherited
        previous_snapshot = json.loads(cache.read_text())["snapshot"]
        empty = directory / "Empty.swift"
        empty.write_text("")
        command.extend(["--module", "Empty", str(empty)])
        assert generate() == inherited
        assert json.loads(cache.read_text())["snapshot"] != previous_snapshot
        del command[-3:]

        # A changed body in a retained file updates the snapshot, but the render
        # cache still preserves identical generated output and its timestamp.
        assert generate() == inherited
        os.utime(declarations_output, ns=(1_000_000_000, 1_000_000_000))
        parent.write_text(parent_source + "func unrelatedBody() -> Int { 1 }\n")
        assert generate() == inherited
        assert declarations_output.stat().st_mtime_ns == 1_000_000_000
        refreshed_cache = cache.read_bytes()
        os.utime(cache, ns=(1_000_000_000, 1_000_000_000))
        assert generate() == inherited
        assert cache.read_bytes() == refreshed_cache
        assert cache.stat().st_mtime_ns == 1_000_000_000

        # Snapshot cache hits restore missing or damaged generated files.
        declarations_output.unlink()
        assert generate() == inherited
        declarations_output.write_text("// damaged output\n")
        assert generate() == inherited
        legacy_cache = json.loads(cache.read_text())
        del legacy_cache["snapshot"]
        cache.write_text(json.dumps(legacy_cache))
        assert generate() == inherited
        assert "snapshot" in json.loads(cache.read_text())

        # Direct mocks depend only on their own module's declarations. Switching
        # inheritance on or off must change the scope of the cached snapshot.
        declarations.write_text("""import Mocksmith
import Dependency
@Mockable protocol Child {}
""")
        direct = generate()
        direct_cache = json.loads(cache.read_text())
        assert direct_cache["usesDependencySources"] is False
        assert all(source["module"] == "Fixture" for source in direct_cache["snapshot"]["sources"])
        cached = cache.read_bytes()
        os.utime(cache, ns=(1_000_000_000, 1_000_000_000))
        parent.write_text(parent.read_text().replace("other", "third"))
        assert generate() == direct
        assert cache.read_bytes() == cached
        assert cache.stat().st_mtime_ns == 1_000_000_000

        declarations.write_text(declarations.read_text().replace("Child {}", "Child: Parent {}"))
        inherited = generate()
        assert "func third() -> Int" in inherited
        assert json.loads(cache.read_text())["usesDependencySources"] is True
        parent.write_text(parent.read_text().replace("third", "fourth"))
        inherited = generate()
        assert "func fourth() -> Int" in inherited
        assert "func third() -> Int" not in inherited

        declarations.write_text(declarations.read_text().replace("Child: Parent {}", "Child {}"))
        assert generate() == direct
        assert json.loads(cache.read_text())["usesDependencySources"] is False
        legacy_cache = json.loads(cache.read_text())
        del legacy_cache["usesDependencySources"]
        cache.write_text(json.dumps(legacy_cache))
        assert generate() == direct
        assert json.loads(cache.read_text())["usesDependencySources"] is False

        # Both active and inactive conditions must fail explicitly: the build
        # tool does not receive the compiler's conditional compilation settings.
        for annotation in ["@Mockable", "@Mockable(.buildPlugin)"]:
            for condition in ["true", "false"]:
                declarations.write_text(f"""import Mocksmith
#if {condition}
{annotation} protocol ConditionalService {{}}
#endif
""")
                result = subprocess.run(command, cwd=root, text=True, capture_output=True)
                assert result.returncode != 0
                assert f"{declarations}:3:1:" in result.stderr
                assert "@Mockable build plugin generation requires an unconditional top-level protocol" in result.stderr

            for declaration in [
                f"{annotation} private protocol PrivateService {{}}",
                f"{annotation} fileprivate protocol FileprivateService {{}}",
                f"enum Scope {{ {annotation} protocol NestedService {{}} }}",
            ]:
                declarations.write_text("import Mocksmith\n" + declaration + "\n")
                result = subprocess.run(command, cwd=root, text=True, capture_output=True)
                assert result.returncode != 0
                assert "@Mockable build plugin generation requires an internal, package, or public top-level protocol" in result.stderr

        declarations.write_text("""import Mocksmith
#if compiler(>=6.0)
    #if canImport(Foundation)
        import Foundation
    #elseif os(Windows)
        import WinSDK
    #else
        let unrelatedNested = 0
    #endif
#elseif os(Linux)
    let unrelatedBranch = 0
#else
    import Foundation
#endif
#if true
    let unrelatedWithoutImports = 0
#endif
@Mockable protocol ConditionalImportService {
    func date() -> Date
}
""")
        generated = generate()
        expected_imports = """#if compiler(>=6.0)
#if canImport(Foundation)
import Foundation
#elseif os(Windows)
import WinSDK
#else
#endif
#elseif os(Linux)
#else
import Foundation
#endif"""
        assert " ".join(expected_imports.split()) in " ".join(generated.split())
        assert "unrelatedNested" not in generated
        assert "unrelatedBranch" not in generated
        assert "unrelatedWithoutImports" not in generated
        assert "#if true" not in generated

        # Compile in isolation so imports from other test files cannot hide a
        # lost condition or an omitted import in the generated source.
        modules = generator.parent / "Modules"
        macro_plugin = generator.parent / "MocksmithMacros-tool"
        if (modules / "Mocksmith.swiftmodule").exists() and macro_plugin.is_file():
            subprocess.run([
                "swiftc", "-typecheck", str(declarations), *map(str, sorted(output.glob("*.generated.swift"))),
                "-module-name", "Fixture", "-swift-version", "6",
                "-I", str(modules),
                "-load-plugin-executable", f"{macro_plugin}#MocksmithMacros",
            ], cwd=root, check=True)
        else:
            print("Skipped isolated typecheck: build the Mocksmith target first.")

    print("Generator selection, render cache, incremental output, and conditional import checks passed.")


if __name__ == "__main__":
    main()
